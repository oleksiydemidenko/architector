using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Architector.Editor
{
    public static class ArchitectorDigest
    {
        public static string Build(
            ArchitectorProjectDocument project,
            IReadOnlyDictionary<string, ArchitectorLayerDocuments> layers)
        {
            var approved = OrderedLayers(project)
                .Where(layer => !string.IsNullOrEmpty(layer.approval?.semanticHash))
                .ToArray();
            if (approved.Length == 0)
                return null;

            var text = new StringBuilder();
            text.Append("# Architecture Digest\n\n");
            text.Append("Generated by Architector from approved baselines. Do not edit this file; approve, revert or revoke layers instead.\n\n");
            text.Append("- Relationships read `A -> B (kind)`: dependency means A depends on B; dataFlow moves data from A to B; event means A emits and B handles; callback means A invokes a callback handled by B.\n");
            text.Append("- Planned: the approved design contains Manual Types that are not linked to code yet.\n");
            text.Append("- Unapproved edits are not shown; a layer may be Changed in the Editor.\n");

            foreach (var layer in approved)
                AppendLayer(text, project, layers, layer);
            return text.ToString();
        }

        private static void AppendLayer(
            StringBuilder text,
            ArchitectorProjectDocument project,
            IReadOnlyDictionary<string, ArchitectorLayerDocuments> layers,
            ArchitectorLayerRecord layer)
        {
            var baseline = layer.approval.baseline ?? new ArchitectorLayerBaselineRecord();
            var planned = baseline.nodes.Any(node => string.Equals(node.type?.mode, "declared", StringComparison.Ordinal));
            text.Append($"\n## {ArchitectorEntryPaths.Describe(project, layer.id)}{(planned ? " (Planned)" : string.Empty)}\n\n");
            if (!string.IsNullOrWhiteSpace(baseline.purpose))
                text.Append($"{OneLine(baseline.purpose)}\n\n");

            var portals = baseline.nodes
                .Where(IsPortal)
                .Select(node => ArchitectorEntryPaths.Describe(project, node.portal.targetLayerId))
                .Where(path => path.Length > 0)
                .OrderBy(path => path, StringComparer.Ordinal)
                .ToArray();
            if (portals.Length > 0)
                text.Append($"Connected layers: {string.Join(", ", portals)}\n\n");

            var nodes = baseline.nodes.Where(node => !IsPortal(node)).ToArray();
            if (nodes.Length > 0)
            {
                text.Append("### Nodes\n\n");
                foreach (var node in nodes)
                    AppendNode(text, node);
                text.Append('\n');
            }

            if (baseline.relationships.Count > 0)
            {
                text.Append("### Relationships\n\n");
                foreach (var edge in baseline.relationships.OrderBy(edge => edge.id, StringComparer.Ordinal))
                {
                    var label = string.IsNullOrWhiteSpace(edge.label) ? string.Empty : $" \"{OneLine(edge.label)}\"";
                    text.Append($"- {Endpoint(project, layers, layer, edge.sourceLayerId, edge.sourceNodeId)} -> " +
                                $"{Endpoint(project, layers, layer, edge.targetLayerId, edge.targetNodeId)} ({edge.kind}){label}\n");
                }
            }
        }

        private static void AppendNode(StringBuilder text, ArchitectorNodeRecord node)
        {
            var mode = node.type?.mode ?? "none";
            var description = mode == "none"
                ? "concept"
                : $"{node.type.kind} `{TypeName(node.type)}`{(mode == "declared" ? " (manual)" : string.Empty)}";
            var responsibility = string.IsNullOrWhiteSpace(node.responsibility) ? string.Empty : $" — {OneLine(node.responsibility)}";
            text.Append($"- **{node.title}**: {description}{responsibility}\n");
            if (node.type?.baseType != null && !string.IsNullOrWhiteSpace(node.type.baseType.name))
                text.Append($"  - base `{ArchitectorTypeReference.FullName(node.type.baseType)}`\n");
            var interfaces = (node.type?.interfaces ?? new List<ArchitectorTypeReferenceRecord>())
                .Select(ArchitectorTypeReference.FullName)
                .OrderBy(name => name, StringComparer.Ordinal)
                .ToArray();
            if (interfaces.Length > 0)
                text.Append($"  - implements {string.Join(", ", interfaces.Select(name => $"`{name}`"))}\n");
            foreach (var member in ArchitectorMemberOrder.SortStable(node.members ?? new List<ArchitectorMemberRecord>()))
                text.Append($"  - `{OneLine(member.declaration)}`\n");
        }

        private static string Endpoint(
            ArchitectorProjectDocument project,
            IReadOnlyDictionary<string, ArchitectorLayerDocuments> layers,
            ArchitectorLayerRecord owner,
            string layerId,
            string nodeId)
        {
            if (string.Equals(layerId, owner.id, StringComparison.Ordinal))
                return owner.approval.baseline.nodes.FirstOrDefault(node => node.id == nodeId)?.title ?? nodeId;
            var remote = project.layers.FirstOrDefault(layer => layer.id == layerId);
            var title = remote?.approval?.baseline?.nodes.FirstOrDefault(node => node.id == nodeId)?.title
                        ?? (layers.TryGetValue(layerId, out var documents)
                            ? documents.semantic.nodes.FirstOrDefault(node => node.id == nodeId)?.title
                            : null)
                        ?? nodeId;
            var path = remote == null ? layerId : ArchitectorEntryPaths.Describe(project, layerId);
            return $"{path}/{title}";
        }

        internal static IEnumerable<ArchitectorLayerRecord> OrderedLayers(ArchitectorProjectDocument project)
        {
            var groups = project.groups.ToDictionary(group => group.id, StringComparer.Ordinal);
            var layers = project.layers.ToDictionary(layer => layer.id, StringComparer.Ordinal);

            IEnumerable<ArchitectorLayerRecord> Visit(IEnumerable<string> groupIds, IEnumerable<string> layerIds)
            {
                foreach (var groupId in groupIds)
                {
                    var group = groups[groupId];
                    foreach (var layer in Visit(group.childGroupIds, group.layerIds))
                        yield return layer;
                }
                foreach (var layerId in layerIds)
                    yield return layers[layerId];
            }

            return Visit(project.rootGroupIds, project.rootLayerIds);
        }

        private static string TypeName(ArchitectorTypeRecord type)
        {
            var name = string.IsNullOrEmpty(type.typeNamespace) ? type.name : $"{type.typeNamespace}.{type.name}";
            return type.genericParameters != null && type.genericParameters.Count > 0
                ? $"{name}<{string.Join(", ", type.genericParameters)}>"
                : name;
        }

        private static string OneLine(string value)
        {
            return ArchitectorNodeResponsibility.Normalize(value);
        }

        private static bool IsPortal(ArchitectorNodeRecord node)
        {
            return string.Equals(node.kind, ArchitectorNodeKinds.LayerPortal, StringComparison.Ordinal);
        }
    }
}
